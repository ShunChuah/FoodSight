"""Regenerate db/schema/tables.md from the live database. Run: python db/dump_schema.py"""
import os
from collections import defaultdict
from pathlib import Path

import psycopg2
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "db" / "schema" / "tables.md"

USER_SCHEMAS = """
    n.nspname !~ '^pg_' AND n.nspname <> 'information_schema'
    AND NOT EXISTS (
        SELECT 1 FROM pg_depend d
        WHERE d.objid = c.oid AND d.deptype = 'e'
    )
"""

COLUMNS_SQL = f"""
    SELECT n.nspname, c.relname, a.attname,
           format_type(a.atttypid, a.atttypmod),
           a.attnotnull,
           pg_get_expr(ad.adbin, ad.adrelid)
    FROM pg_attribute a
    JOIN pg_class c ON c.oid = a.attrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
    WHERE c.relkind = 'r' AND a.attnum > 0 AND NOT a.attisdropped AND {USER_SCHEMAS}
    ORDER BY n.nspname, c.relname, a.attnum
"""

CONSTRAINTS_SQL = f"""
    SELECT n.nspname, c.relname, con.contype, con.conname, pg_get_constraintdef(con.oid)
    FROM pg_constraint con
    JOIN pg_class c ON c.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE con.contype IN ('p', 'f', 'u', 'c') AND {USER_SCHEMAS}
    ORDER BY n.nspname, c.relname, con.contype, con.conname
"""

INDEXES_SQL = """
    SELECT schemaname, tablename, indexdef
    FROM pg_indexes i
    WHERE schemaname !~ '^pg_' AND schemaname <> 'information_schema'
      AND NOT EXISTS (
          SELECT 1 FROM pg_constraint con WHERE con.conname = i.indexname
      )
    ORDER BY schemaname, tablename, indexname
"""

TRIGGERS_SQL = f"""
    SELECT n.nspname, c.relname, pg_get_triggerdef(t.oid)
    FROM pg_trigger t
    JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE NOT t.tgisinternal AND {USER_SCHEMAS}
    ORDER BY n.nspname, c.relname, t.tgname
"""

# The functions the triggers run, so what a trigger does is visible too
TRIGGER_FUNCTIONS_SQL = """
    SELECT DISTINCT p.oid::regprocedure::text, pg_get_functiondef(p.oid)
    FROM pg_trigger t
    JOIN pg_proc p ON p.oid = t.tgfoid
    WHERE NOT t.tgisinternal
    ORDER BY 1
"""

ENUMS_SQL = """
    SELECT n.nspname, t.typname, string_agg(e.enumlabel, ', ' ORDER BY e.enumsortorder)
    FROM pg_type t
    JOIN pg_enum e ON e.enumtypid = t.oid
    JOIN pg_namespace n ON n.oid = t.typnamespace
    GROUP BY 1, 2 ORDER BY 1, 2
"""

CONSTRAINT_ORDER = {"p": 0, "u": 1, "f": 2, "c": 3}


def cell(value):
    return "" if value is None else str(value).replace("|", "\\|")


def main():
    load_dotenv(ROOT / ".env")
    conn = psycopg2.connect(
        host=os.getenv("DB_HOST", "localhost"),
        port=int(os.getenv("DB_PORT", 5432)),
        dbname=os.getenv("DB_NAME", "foodsight"),
        user=os.getenv("DB_USER", "postgres"),
        password=os.getenv("DB_PASSWORD", ""),
    )
    try:
        with conn.cursor() as cur:
            cur.execute("SELECT extname, extversion FROM pg_extension ORDER BY 1")
            extensions = cur.fetchall()
            cur.execute(ENUMS_SQL)
            enums = cur.fetchall()
            cur.execute(COLUMNS_SQL)
            columns = defaultdict(list)
            for schema, table, *rest in cur.fetchall():
                columns[(schema, table)].append(rest)
            cur.execute(CONSTRAINTS_SQL)
            constraints = defaultdict(list)
            for schema, table, kind, _name, definition in cur.fetchall():
                constraints[(schema, table)].append((CONSTRAINT_ORDER[kind], definition))
            cur.execute(INDEXES_SQL)
            indexes = defaultdict(list)
            for schema, table, definition in cur.fetchall():
                if (schema, table) in columns:
                    indexes[(schema, table)].append(definition)
            cur.execute(TRIGGERS_SQL)
            triggers = defaultdict(list)
            for schema, table, definition in cur.fetchall():
                triggers[(schema, table)].append(definition)
            cur.execute(TRIGGER_FUNCTIONS_SQL)
            trigger_functions = cur.fetchall()
    finally:
        conn.close()

    lines = [
        "# Database tables",
        "",
        "Generated by `python db/dump_schema.py` from the live database. Do not edit by hand:",
        "change the database with a file in `db/migrations/`, then regenerate this file.",
        "",
        "## Extensions",
        "",
        *[f"- `{name}` {version}" for name, version in extensions],
        "",
    ]
    if enums:
        lines += ["## Enum types", ""]
        lines += [f"- `{schema}.{name}`: {labels}" for schema, name, labels in enums]
        lines.append("")
    lines += ["## Tables", ""]
    lines += [f"- [{s}.{t}](#{s}{t})" for s, t in columns]
    lines.append("")

    for (schema, table), cols in columns.items():
        lines += [
            f"## {schema}.{table}",
            "",
            "| Column | Type | Required | Default |",
            "|---|---|---|---|",
        ]
        for name, data_type, not_null, default in cols:
            required = "yes" if not_null else "no"
            lines.append(f"| `{name}` | {cell(data_type)} | {required} | {cell(default)} |")
        lines.append("")
        for _order, definition in sorted(constraints[(schema, table)]):
            lines.append(f"- {definition}")
        for definition in indexes[(schema, table)]:
            lines.append(f"- {definition}")
        for definition in triggers[(schema, table)]:
            lines.append(f"- {definition}")
        lines.append("")

    if trigger_functions:
        lines += ["## Trigger functions", ""]
        for name, definition in trigger_functions:
            lines += [f"### {name}", "", "```sql", definition.strip(), "```", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(columns)} tables")


if __name__ == "__main__":
    main()
